const stars0 = document.querySelectorAll(".star0 i");
stars0.forEach((star0, index1) => {
    star0.addEventListener("click", () => {
        stars0.forEach((star0, index2) => {
            index1 >= index2 ? star0.classList.add("active") : star0.classList.remove("active")
        })
            
    })
})
